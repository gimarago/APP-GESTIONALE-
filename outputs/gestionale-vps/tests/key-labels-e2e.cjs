const {selectAgenda}=require('./navigation-helpers.cjs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {pathToFileURL}=require('node:url');
const path=require('node:path'),fs=require('node:fs'),os=require('node:os'),assert=require('node:assert/strict');

(async()=>{
  const root=path.resolve(__dirname,'..'),dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'officina-labels-'));
  const {createApplication}=await import(pathToFileURL(path.join(root,'server/server.mjs')));
  const {addUser}=await import(pathToFileURL(path.join(root,'server/database.mjs')));
  const app=await createApplication({root,dataDir,origin:'http://127.0.0.1:8134',env:{NODE_ENV:'test'}});
  await addUser(app.db,'label-test','test-password-1234','admin');
  await new Promise(resolve=>app.server.listen(8134,'127.0.0.1',resolve));
  const browser=await chromium.launch({...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{}),headless:true});
  const page=await browser.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.stack));
  page.on('dialog',dialog=>dialog.accept());
  const frame=()=>page.frames().find(item=>item.url().endsWith('/legacy'));
  const ready=()=>page.waitForFunction(()=>document.querySelector('iframe')?.contentWindow?.WorkshopCloud&&!document.querySelector('iframe').contentWindow.WorkshopCloud.initializing);
  try{
    await page.goto('http://127.0.0.1:8134');
    await page.locator('#username').fill('label-test');
    await page.locator('#password').fill('test-password-1234');
    await page.locator('#loginForm button[type="submit"]').click();await ready();
    const f=frame();
    const logoBefore=await f.evaluate(()=>localStorage.getItem('officinaWorkshopLogo'));
    await f.locator('#shopLogoInput').setInputFiles({name:'logo.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"></svg>')});
    assert.equal(await f.evaluate(()=>localStorage.getItem('officinaWorkshopLogo')),logoBefore,'unsupported SVG must not reach shared data');
    await f.locator('#shopLogoInput').setInputFiles({name:'logo.png',mimeType:'image/png',buffer:fs.readFileSync(path.join(root,'cloud-icon-180.png'))});
    await f.waitForFunction(()=>localStorage.getItem('officinaWorkshopLogo')?.startsWith('data:image/png;base64,'));
    await selectAgenda(f,'parking');
    await f.locator('.parking-head [data-cloud-open="parkingModal"]').click();
    await f.locator('#parkCustomer').fill('Carlo Etichetta');
    await f.locator('#parkPlate').fill('AA123BB');
    await f.locator('#parkVehicle').fill('Fiat Panda');
    await f.locator('#parkWork').fill('Lavoro completato');
    await f.locator('#parkWorkDone').check();
    await f.locator('#addParkingWork').click();
    await f.locator('.parking-work-description').fill('Sostituire pastiglie freno');
    await f.locator('#parkingForm button', {hasText:'Stampa etichetta'}).click();
    let preview=f.locator('#workshopLabelPreview');await preview.waitFor();
    assert.match(await preview.locator('#workshopLabelPaper').innerText(),/Carlo Etichetta/);
    assert.match(await preview.locator('#workshopLabelPaper').innerText(),/AA123BB/);
    assert.match(await preview.locator('.key-label-logo').getAttribute('src'),/^data:image\/png;base64,/);
    assert.match(await preview.locator('#workshopLabelPaper').innerText(),/Sostituire pastiglie freno/);
    assert.doesNotMatch(await preview.locator('#workshopLabelPaper').innerText(),/Lavoro completato/);
    assert.equal(await preview.locator('.key-label-extra span').count(),2);
    if(process.env.LABEL_SCREENSHOT)await preview.locator('#workshopLabelPaper').screenshot({path:process.env.LABEL_SCREENSHOT});
    await preview.locator('#workshopLabelWidth').selectOption('58');
    assert.match(await f.locator('#workshopLabelStyle').textContent(),/@page\{size:58mm \d+mm;margin:0\}/);
    await preview.locator('#workshopLabelClose').click();
    await f.locator('#parkingForm button[type="submit"]').click();
    const parkingButton=f.locator('.parking-row [data-print-parking-label]').last();await parkingButton.waitFor();await parkingButton.click();
    preview=f.locator('#workshopLabelPreview');await preview.waitFor();
    assert.match(await preview.locator('#workshopLabelPaper').innerText(),/Sostituire pastiglie freno/);
    assert.doesNotMatch(await preview.locator('#workshopLabelPaper').innerText(),/Lavoro completato/);
    await preview.locator('#workshopLabelClose').click();
    console.log('PASS parking form and saved row print pending work on thermal-size label');

    await selectAgenda(f);await f.locator('#agenda').waitFor({state:'visible'}); await f.evaluate(() => { document.getElementById('appDate').value = localCreationDate(); openModal('appointmentModal'); });
    await f.locator('#appCustomer').fill('Mario Accettazione');
    await f.locator('#appPlate').fill('BB456CC');
    await f.locator('#appointmentWorkLines [data-description]').fill('Lavoro già fatto');
    await f.locator('#appointmentForm button[type="submit"]').click();
    await f.evaluate(()=>openAcceptanceEditorForRow(document.querySelector('#agendaRows tr:not(.agenda-empty)')));
    await f.locator('#addAcceptanceLine').click();
    await f.locator('.acceptance-description').last().fill('Montare pneumatici');
    await f.locator('.acceptance-done').first().check();
    await f.locator('#acceptanceForm button', {hasText:'Stampa etichetta'}).click();
    preview=f.locator('#workshopLabelPreview');await preview.waitFor();
    assert.match(await preview.locator('#workshopLabelPaper').innerText(),/Montare pneumatici/);
    assert.doesNotMatch(await preview.locator('#workshopLabelPaper').innerText(),/Lavoro già fatto/);
    await preview.locator('#workshopLabelClose').click();
    await f.locator('#acceptanceForm button', {hasText:'Stampa scheda'}).click();
    await f.locator('#workshopPrintToolbar button', {hasText:'Stampa etichetta'}).click();
    assert.equal(await f.locator('#workshopPrintPreview').count(),0);
    assert.equal(await f.locator('#workshopLabelPreview').count(),1);
    assert.equal(await f.evaluate(()=>[...document.querySelectorAll('style')].filter(item=>item.textContent.includes('#workshopPrintPaper{background:white')).length),0);
    assert.match(await f.locator('#workshopLabelStyle').textContent(),/@page\{size:80mm \d+mm;margin:0\}/);
    console.log('PASS acceptance form and sheet preview open the matching key label');
    assert.deepEqual(errors,[]);
  }finally{
    await browser.close();await new Promise(resolve=>app.server.close(resolve));app.db.close();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
