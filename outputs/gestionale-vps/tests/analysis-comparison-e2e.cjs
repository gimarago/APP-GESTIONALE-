const {selectAgenda}=require('./navigation-helpers.cjs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const {pathToFileURL} = require('node:url');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), net = require('node:net');
const assert = require('node:assert/strict');

(async () => {
  const root = path.resolve(__dirname, '..');
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'officina-analysis-compare-'));
  const probe = net.createServer();
  await new Promise(resolve => probe.listen(0, '127.0.0.1', resolve));
  const port = probe.address().port;
  await new Promise(resolve => probe.close(resolve));
  const origin = 'http://127.0.0.1:' + port;
  const {createApplication} = await import(pathToFileURL(path.join(root, 'server/server.mjs')));
  const {addUser} = await import(pathToFileURL(path.join(root, 'server/database.mjs')));
  const app = await createApplication({root, dataDir, origin, env:{NODE_ENV:'test'}});
  await addUser(app.db, 'analysis-test', 'test-password-1234', 'admin');
  await new Promise(resolve => app.server.listen(port, '127.0.0.1', resolve));
  const browser = await chromium.launch({...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {}), headless:true});
  const page = await browser.newPage({viewport:{width:1436, height:1100}}), errors = [];
  page.on('pageerror', error => errors.push(error.stack));
  page.on('dialog', dialog => dialog.accept());
  const frame = () => page.frames().find(item => item.url().endsWith('/legacy'));
  const ready = () => page.waitForFunction(() => document.querySelector('iframe')?.contentWindow?.WorkshopCloud?.initializing === false);
  const flush = () => page.evaluate(() => WorkshopCloudHost.flush());
  const pieValue = (f, id) => f.locator('#' + id + ' .analysis-pie-total').textContent();
  let f;
  try {
    await page.goto(origin);
    await page.locator('#username').fill('analysis-test');
    await page.locator('#password').fill('test-password-1234');
    await page.locator('#loginForm button[type="submit"]').click();
    await ready(); f = frame();
    const today = await f.evaluate(() => workshopToday);
    const year = Number(today.slice(0, 4));
    async function completedWork(customer, date, amount, profit) {
      await selectAgenda(f);
      await f.locator('#agenda').waitFor({state:'visible'}); await f.evaluate(() => { document.getElementById('appDate').value = localCreationDate(); openModal('appointmentModal'); });
      await f.locator('#appDate').fill(date);
      await f.locator('#appCustomer').fill(customer);
      await f.locator('#appPlate').fill(customer === 'Lavoro corrente' ? 'AC123AA' : 'AP123AA');
      await f.locator('#appointmentWorkLines [data-description]').fill('Diagnosi motore');
      await f.locator('#appointmentWorkLines [data-amount]').fill(String(amount));
      await f.locator('#appointmentForm button[type="submit"]').click();
      const row = f.locator('#agendaRows tr:not(.agenda-empty)').filter({hasText:customer});
      await row.evaluate(element => window.openAcceptanceEditorForRow(element));
      await f.locator('#acceptanceLines .acceptance-amount').first().fill(String(amount));
      await f.locator('#acceptanceLines .acceptance-profit').first().fill(String(profit));
      await f.locator('#acceptanceForm button[type="submit"]').click();
      const saved = await row.evaluate(element => JSON.parse(element.dataset.acceptanceLines || '[]'));
      assert.equal(saved[0]?.amount, amount, 'acceptance amount remains unchanged for ' + customer);
      assert.equal(Number(saved[0]?.profit), profit, 'acceptance profit is saved for ' + customer + ': ' + JSON.stringify(saved));
      await row.locator('.status-select').selectOption('COMPLETATO');
      await flush();
    }
    await completedWork('Lavoro corrente', year + '-06-15', 300, 100);
    await completedWork('Lavoro precedente', (year - 1) + '-06-15', 200, 80);
    await f.locator('.nav [data-view="analysis"]').click();
    await f.evaluate(() => { showPage('analysis'); renderDataAnalysis(); });
    assert.equal(await f.locator('#analysisComparePanel').isVisible(), true, 'comparison is active by default');
    assert.equal(await f.locator('#analysisCompareEnabled').count(), 0, 'comparison cannot be switched off');
    assert.equal(await f.locator('#analysisCompareControls').isVisible(), true);
    assert.equal(await f.locator('#analysisComparePeriod').inputValue(), 'lastYear');
    assert.equal(await f.locator('#analysisIncomePeriod').inputValue(), 'year', 'work value filter defaults to this year');
    const periodFiltersAligned = await f.evaluate(() => Math.abs(document.getElementById('analysisIncomePeriod').getBoundingClientRect().top - document.getElementById('analysisComparePeriod').getBoundingClientRect().top) <= 1);
    assert.equal(periodFiltersAligned, true, 'work and comparison periods share one aligned row');
    const priorYearEnd = today.slice(8, 10) + '/' + today.slice(5, 7) + '/' + (year - 1);
    assert.equal(await f.locator('#analysisCompareChartHint').innerText(), 'Anno precedente · 01/01/' + (year - 1) + ' – ' + priorYearEnd, 'previous-year comparison ends on the same day and month');
    const initialState = await f.evaluate(() => ({rows:[...document.querySelectorAll('#agendaRows tr:not(.agenda-empty)')].map(row=>({date:row.dataset.date, lines:row.dataset.acceptanceLines, amount:row.cells[4]?.textContent, status:row.querySelector('.status-select')?.value})), ledger:window.WorkshopLedgerCash.snapshot().entries.map(entry=>({amount:entry.amount, profit:entry.state.profit, date:entry.date})), baseline:window.getIncomeReportBaseline?.()}));
    assert.match(await pieValue(f, 'analysisPie'), /300,00/, JSON.stringify(initialState));
    assert.equal(await f.locator('#analysisComparePanel').isVisible(), true);
    assert.match(await pieValue(f, 'analysisPie'), /300,00/);
    assert.match(await pieValue(f, 'analysisComparePie'), /200,00/);
    assert.equal(await f.locator('#analysisRevenueGrowthValue').innerText(), '+50,0%');
    assert.match(await f.locator('#analysisRevenueGrowthDetail').innerText(), /€ 300,00.*€ 200,00/);
    const summaryAboveComparison = await f.evaluate(() => document.getElementById('analysisCompareChartSummary').getBoundingClientRect().bottom <= document.getElementById('analysisCompareChartToggle').getBoundingClientRect().top);
    assert.equal(summaryAboveComparison, true, 'comparison summary appears above its chart');
    const summaryAboveMain = await f.evaluate(() => document.getElementById('analysisChartSummary').getBoundingClientRect().bottom <= document.getElementById('analysisChartToggle').getBoundingClientRect().top && document.getElementById('analysisChartSummary').parentElement.id === 'analysisMainChartPanel');
    assert.equal(summaryAboveMain, true, 'main summary appears directly above its chart inside its comparison panel');
    assert.equal(await f.locator('#analysisCompareChartTitle').count(), 0, 'duplicate comparison chart heading is removed');
    const layout = await f.evaluate(() => {
      const first = document.querySelector('#analysisChartToggle').getBoundingClientRect();
      const second = document.querySelector('#analysisCompareChartToggle').getBoundingClientRect();
      const card = document.querySelector('#analysisChartToggle').closest('.analysis-card');
      return {first:{left:first.left,right:first.right,top:first.top}, second:{left:second.left,right:second.right,top:second.top}, overflow:card.scrollWidth - card.clientWidth};
    });
    assert.ok(layout.first.right < layout.second.left, 'both pies are side by side on desktop: ' + JSON.stringify(layout));
    assert.ok(layout.overflow <= 1, 'comparison does not overflow the card');
    if (process.env.ANALYSIS_SCREENSHOT_DIR) await f.locator('#analysisCompareCharts').screenshot({path:path.join(process.env.ANALYSIS_SCREENSHOT_DIR, 'analysis-compare-desktop.png')});
    await f.locator('#analysisCompareChartToggle').click();
    const profitState = await f.evaluate(() => ({ledger:window.WorkshopLedgerCash.snapshot().entries.map(entry => ({customer:entry.customer, profit:entry.state.profit, key:entry.key, lines:entry.lines})), rows:[...document.querySelectorAll('#agendaRows tr:not(.agenda-empty)')].map(row=>({lines:row.dataset.acceptanceLines, date:row.dataset.date})), current:document.getElementById('analysisChartSummary').textContent, comparison:document.getElementById('analysisCompareChartSummary').textContent}));
    assert.match(await f.locator('#analysisChartTitle').innerText(), /Profitto/);
    assert.match(await f.locator('#analysisComparePieTitle').textContent(), /Profitto/);
    assert.match(await f.locator('#analysisPie').textContent(), /100,00/, JSON.stringify(profitState));
    assert.match(await pieValue(f, 'analysisComparePie'), /80,00/);
    await f.locator('#analysisChartToggle').click();
    assert.match(await pieValue(f, 'analysisPie'), /300,00/);
    assert.match(await pieValue(f, 'analysisComparePie'), /200,00/);
    console.log('PASS current and prior periods display real totals side by side and either pie switches both to profit');

    await f.locator('#analysisComparePeriod').selectOption('custom');
    await f.locator('#analysisCompareStart').fill((year - 1) + '-06-15');
    await f.locator('#analysisCompareEnd').fill((year - 1) + '-06-15');
    assert.match(await pieValue(f, 'analysisComparePie'), /200,00/);
    await f.locator('#analysisCompareStart').fill((year - 1) + '-06-16');
    assert.match(await f.locator('#analysisCompareChartSummary').innerText(), /intervallo personalizzato valido/i);
    await f.locator('#analysisCompareEnd').fill((year - 1) + '-06-17');
    assert.match(await f.locator('#analysisComparePie').textContent(), /Nessun dato/);
    assert.equal(await f.locator('#analysisRevenueGrowthValue').innerText(), '—', 'growth is undefined when comparison revenue is zero');
    assert.match(await f.locator('#analysisRevenueGrowthDetail').innerText(), /pari a zero/i);
    await f.locator('#analysisComparePeriod').selectOption('lastYear');
    assert.match(await pieValue(f, 'analysisComparePie'), /200,00/);
    await f.locator('#analysisIncomePeriod').selectOption('all');
    await f.locator('#analysisComparePeriod').selectOption('previous');
    assert.match(await pieValue(f, 'analysisPie'), /500,00/);
    assert.match(await pieValue(f, 'analysisComparePie'), /200,00/);
    assert.match(await f.locator('#analysisCompareChartHint').innerText(), /Anno precedente/);
    console.log('PASS custom dates, empty periods and all-time comparison use real recorded data');

    await page.setViewportSize({width:390, height:844});
    const mobile = await f.evaluate(() => {
      const card = document.querySelector('#analysisChartToggle').closest('.analysis-card');
      const first = document.querySelector('#analysisChartToggle').getBoundingClientRect();
      const second = document.querySelector('#analysisCompareChartToggle').getBoundingClientRect();
      return {overflow:card.scrollWidth - card.clientWidth, firstBottom:first.bottom, secondTop:second.top};
    });
    assert.ok(mobile.overflow <= 1, 'both mobile pies fit without horizontal overflow');
    assert.ok(mobile.secondTop > mobile.firstBottom, 'mobile pies stack vertically');
    if (process.env.ANALYSIS_SCREENSHOT_DIR) await f.locator('#analysisCompareCharts').screenshot({path:path.join(process.env.ANALYSIS_SCREENSHOT_DIR, 'analysis-compare-mobile.png')});
    await page.reload(); await ready(); f = frame();
    await f.locator('.nav [data-view="analysis"]').click();
    await f.evaluate(() => { showPage('analysis'); renderDataAnalysis(); });
    assert.equal(await f.locator('#analysisIncomePeriod').inputValue(), 'year');
    assert.equal(await f.locator('#analysisComparePanel').isVisible(), true);
    assert.equal(await f.locator('#analysisComparePeriod').inputValue(), 'lastYear');
    assert.match(await pieValue(f, 'analysisPie'), /300,00/);
    assert.match(await pieValue(f, 'analysisComparePie'), /200,00/);
    assert.equal(await f.locator('#analysisRevenueGrowthValue').innerText(), '+50,0%');
    assert.deepEqual(errors, []);
    console.log('PASS comparison remains correct after refresh with responsive layout and no browser errors');
  } finally {
    await browser.close();
    await app.close();
  }
})().catch(error => {console.error(error); process.exitCode = 1;});
