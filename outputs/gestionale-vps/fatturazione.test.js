const assert = require('node:assert/strict');
const {totals, validate, xml, vatValid} = require('./fatturazione');
const seller = {name:'Officina & test',vat:'01114601006',address:'Via Roma 1',zip:'00100',city:'Roma',province:'RM'};
const doc = {type:'TD01',date:'2026-09-11',payment:'MP05',customer:{...seller,code:'0000000'},lines:[{description:'Lavoro',quantity:2,price:100,discount:10,vat:22},{description:'Ricambio',quantity:1,price:20,discount:0,vat:10}],number:'1/2026',progressive:'2026000001'};
assert(vatValid(seller.vat));
assert(!vatValid('00000000000'));
assert.equal(totals(doc.lines).total,241.6);
const grossLines=[{description:'Pneumatici',quantity:4,price:160/1.22,grossPrice:160,discount:0,vat:22}];
assert.equal(totals(grossLines).total,640);
assert.equal(totals(grossLines).net,524.59);
assert.equal(totals(grossLines).tax,115.41);
assert.equal(totals([{...grossLines[0],discount:10}]).total,576);
assert.equal(totals(JSON.parse(JSON.stringify(grossLines))).total,640);
assert.deepEqual(validate(doc,seller),[]);
assert(xml(doc,seller).includes('Officina &amp; test'));
assert(validate({...doc,date:'2026-02-30'},seller).length);
assert(validate({...doc,type:'TD04'},seller).length);
assert.deepEqual(validate({...doc,type:'TD04',reference:'12/2026',referenceDate:'2026-01-02'},seller),[]);
assert(validate({...doc,lines:[{...doc.lines[0],quantity:-1}]},seller).length);
console.log('8 controlli superati: IVA, sconti, partita IVA, date, note di credito, quantità e escaping XML. Non costituiscono validazione SdI/XSD.');
